"""Writes js/maprooms.js: the named rooms of the twelve generated arenas (from newmaps.py), so the game can dress
each room for what it is. Run from the tools folder: python exportrooms.py"""
import json, os
from newmaps import SPECS

here = os.path.dirname(os.path.abspath(__file__))
rooms = {}
for spec in SPECS:
    # [name, x0, z0, x1, z1] in grid cells, inclusive
    rooms[spec['id']] = [[r[0], r[2], r[3], r[2] + r[4] - 1, r[3] + r[5] - 1] for r in spec['rooms']]
out = os.path.join(here, '..', 'js', 'maprooms.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/exportrooms.py from tools/newmaps.py: named rooms of the generated arenas.\n')
    f.write('XH.MAPROOMS = ' + json.dumps(rooms, separators=(',', ':')) + ';\n')
print('wrote', out)
